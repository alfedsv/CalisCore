import Foundation

/// Описание сцены: как расположить камеру относительно 3D-модели.
///
/// Используется для настройки начального вида: расстояние до модели,
/// углы обзора и точка, на которую смотрит камера.
struct SceneModel {

    /// Имя сцены (используется как идентификатор).
    let name: String

    /// Множитель радиуса орбиты.
    ///
    /// Показывает, на сколько радиусов модели нужно отодвинуть камеру.
    /// Например, `2.0` — камера на расстоянии двух радиусов модели.
    ///
    /// - `1.5` — камера очень близко, модель «на весь экран»
    /// - `2.0–2.5` — нормальный обзор всей модели
    /// - `4.0+` — модель мелкая, много пустого места
    let radiusOrbitMul: Float

    /// Поворот камеры вокруг вертикальной оси, в радианах.
    ///
    /// Положительное значение — камера смещается вправо от модели
    /// (модель видна с левого бока), отрицательное — наоборот.
    ///
    /// | Радианы | Градусы | Положение камеры |
    /// |---------|---------|------------------|
    /// | `0`     | 0°      | спереди (по +Z)  |
    /// | `π/4`   | 45°     | спереди-справа   |
    /// | `π/2`   | 90°     | справа           |
    /// | `π`     | 180°    | сзади            |
    /// | `-π/4`  | −45°    | спереди-слева    |
    /// | `-π/2`  | −90°    | слева            |
    let azimuth: Float

    /// Угол над горизонтом, в радианах.
    ///
    /// `0` — камера на уровне горизонта, положительное — выше,
    /// отрицательное — ниже.
    ///
    /// | Радианы | Градусы | Положение камеры      |
    /// |---------|---------|-----------------------|
    /// | `0`     | 0°      | на уровне центра      |
    /// | `π/8`   | 22.5°   | чуть сверху           |
    /// | `π/6`   | 30°     | сверху                |
    /// | `π/4`   | 45°     | заметно сверху        |
    /// | `π/3`   | 60°     | почти сверху          |
    /// | `-π/6`  | −30°    | снизу (снизу вверх)   |
    let elevation: Float

    /// Смещение точки взгляда по оси X, в радиусах модели.
    ///
    /// - `0` — смотрит точно в центр модели
    /// - `+0.5` — смотрит правее центра
    /// - `-0.5` — смотрит левее центра
    let scaledCenterMulX: Float

    /// Смещение точки взгляда по оси Y, в радиусах модели.
    ///
    /// - `0` — смотрит точно в центр модели
    /// - `0.5` — смотрит на 0.5 радиуса выше центра
    /// - `-0.3` — смотрит ниже центра
    let scaledCenterMulY: Float

    /// Смещение точки взгляда по оси Z, в радиусах модели.
    ///
    /// - `0` — смотрит точно в центр модели
    /// - `+0.5` — точка фокуса смещена вперёд (от камеры)
    /// - `-0.5` — точка фокуса смещена назад (к камере)
    let scaledCenterMulZ: Float
}
